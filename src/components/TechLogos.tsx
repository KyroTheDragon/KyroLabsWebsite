export interface TechBadgeProps {
  name: string;
  showLabel?: boolean;
}

export function TechBadge({ name, showLabel = true }: TechBadgeProps) {
  const norm = name.toLowerCase().trim();

  let Icon = null;
  let label = name;

  if (norm.includes("go") && !norm.includes("mongo")) {
    Icon = GoLogo;
    label = "Go";
  } else if (norm.includes("node")) {
    Icon = NodeLogo;
    label = "Node.js";
  } else if (norm.includes("typescript")) {
    Icon = TypeScriptLogo;
    label = "TypeScript";
  } else if (norm.includes("react")) {
    Icon = ReactLogo;
    label = "React";
  } else if (norm.includes("postgres")) {
    Icon = PostgreSQLLogo;
    label = "PostgreSQL";
  } else if (norm.includes("timescale")) {
    Icon = TimescaleLogo;
    label = "TimescaleDB";
  } else if (norm.includes("docker")) {
    Icon = DockerLogo;
    label = "Docker";
  } else if (norm.includes("redis")) {
    Icon = RedisLogo;
    label = "Redis";
  } else if (norm.includes("tailwind")) {
    Icon = TailwindLogo;
    label = "Tailwind CSS";
  } else if (norm.includes("vite")) {
    Icon = ViteLogo;
    label = "Vite";
  } else if (norm.includes("fastify")) {
    Icon = FastifyLogo;
    label = "Fastify";
  } else if (norm.includes("next")) {
    Icon = NextLogo;
    label = "Next.js";
  } else if (norm.includes("websocket")) {
    Icon = WebSocketLogo;
    label = "WebSockets";
  } else if (norm.includes("github") || norm.includes("action")) {
    Icon = GitHubActionsLogo;
    label = "GitHub Actions";
  } else if (norm.includes("local") || norm.includes("worker") || norm.includes("index") || norm.includes("sse")) {
    Icon = LocalFirstLogo;
    label = name;
  }

  return (
    <span
      title={label}
      aria-label={label}
      className="inline-flex items-center gap-1.5 rounded-xl border border-zinc-200 hover:border-zinc-300 dark:border-zinc-800 dark:hover:border-zinc-700 bg-white dark:bg-zinc-900/60 px-2.5 py-1 text-xs font-medium text-zinc-800 dark:text-zinc-200 transition-colors shadow-[0_1px_2px_rgba(0,0,0,0.03)]"
    >
      {Icon && <Icon className="size-3.5 shrink-0" />}
      {showLabel && <span>{label}</span>}
    </span>
  );
}
